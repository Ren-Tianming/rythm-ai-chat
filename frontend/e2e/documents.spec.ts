import { test, expect } from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'

test('register, login, RAG documents, long output, continue, stop and history', async ({ page }) => {
  const failures: string[] = []
  page.on('pageerror', error => failures.push(error.message))
  await page.addInitScript(() => localStorage.setItem('rythm_locale', 'en-US'))
  await page.goto('/')
  await page.locator('.auth-tabs').getByRole('button', { name: 'Create account', exact: true }).click()
  await page.getByLabel('Display name', { exact: true }).fill('Browser tester')
  await page.getByLabel('Email', { exact: true }).fill('browser@example.com')
  await page.getByLabel('Password', { exact: true }).fill('Secure_Browser_Pass_2026!')
  await page.getByLabel('Confirm password', { exact: true }).fill('Secure_Browser_Pass_2026!')
  await page.getByRole('checkbox').check()
  await page.locator('form').getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByText('Verification email sent. Check your inbox.')).toBeVisible()
  const token = JSON.parse(fs.readFileSync(process.env.E2E_MAIL_FILE!, 'utf-8')).token
  await page.goto(`/#verify=${token}`)
  await page.reload() // Email links open a fresh document; hash-only navigation does not remount React.
  await expect(page.getByText('Email verified. You can now sign in.')).toBeVisible()
  await page.getByLabel('Email', { exact: true }).fill('browser@example.com')
  await page.getByLabel('Password', { exact: true }).fill('Secure_Browser_Pass_2026!')
  await page.locator('form').getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.locator('.chat-layout')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Attach files', exact: true })).toBeEnabled()
  const attachment = page.locator('input[type=file]')
  await attachment.setInputFiles([
    { name: 'budget.txt', mimeType: 'text/plain', buffer: Buffer.from('ORION budget is 4200000 yen. Deadline is November 30.') },
    { name: 'schedule.md', mimeType: 'text/markdown', buffer: Buffer.from('# ORION\n\nORION starts in November. Budget is 4200000 yen.') },
  ])
  await expect(page.locator('.attachment--ready')).toHaveCount(2)
  await expect(page.locator('.attachment input:checked')).toHaveCount(2)
  await page.getByRole('button', { name: 'Preview: budget.txt', exact: true }).click()
  await expect(page.getByRole('dialog').getByText(/4200000/)).toBeVisible()
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click()
  const send = async (text: string) => {
    await page.locator('textarea').fill(text)
    await page.getByRole('button', { name: 'Send', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Stop', exact: true })).toBeHidden()
  }
  await send('What is the ORION budget?')
  await expect(page.locator('.message-sources')).toHaveCount(1)
  await expect(page.locator('.message-sources details')).toHaveCount(2)
  await page.locator('.message-sources summary').first().click()
  await expect(page.locator('.message-sources blockquote').first()).toContainText('4200000')
  await attachment.setInputFiles(['plan.png', 'scan.pdf', 'text.pdf'].map(name => path.join(process.env.E2E_FIXTURE_DIR!, name)))
  await expect(page.locator('.attachment--ready')).toHaveCount(5)
  await expect(page.getByText('This model supports OCR text only; visual image understanding is unavailable.')).toBeVisible()
  await page.getByRole('button', { name: 'Preview: plan.png', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('img', { name: 'plan.png', exact: true })).toBeVisible()
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click()
  await page.locator('.model-select select').selectOption({ label: 'Test Vision' })
  await send('What is the ORION budget in these files?')
  await expect(page.locator('.message-sources').last()).toContainText('Page 1')
  await expect(page.locator('.message-sources').last()).toContainText('Image supplied for visual analysis')
  await page.screenshot({ path: 'test-results/rag-desktop.png', fullPage: true })
  await page.reload()
  await expect(page.locator('.conversation-item')).toHaveCount(1)
  await page.locator('.conversation-item > button').first().click()
  await expect(page.locator('.message-sources')).toHaveCount(2)
  await expect(page.locator('.attachment--ready')).toHaveCount(5)
  // File selection is deliberately reset when reopening a conversation.
  await page.getByRole('checkbox', { name: 'Use for this question: budget.txt' }).check()
  await send('How tall is Mount Everest?')
  await expect(page.locator('.message--assistant').last()).toContainText('sufficient relevant evidence')
  await page.getByRole('checkbox', { name: 'Use for this question: budget.txt' }).uncheck()
  await page.locator('.model-select select').selectOption({ label: 'Test Vision' })
  await send('Hello ordinary chat')
  await expect(page.locator('.message--assistant').last()).toContainText('ordinary chat response')
  await send('LONG complete report')
  await expect(page.locator('.message--assistant').last()).toContainText('output budget limit')
  expect((await page.locator('.message--assistant .markdown').last().innerText()).trim().split(/\s+/).length).toBeGreaterThan(1024)
  await page.getByRole('button', { name: 'Continue generating', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Stop', exact: true })).toBeHidden()
  await expect(page.locator('.message--assistant').last()).toContainText('ordinary chat response')
  await page.locator('textarea').fill('SLOW response to stop')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.locator('.message--assistant').last()).toContainText('partial response')
  await page.getByRole('button', { name: 'Stop', exact: true }).click()
  await expect(page.locator('.message--assistant').last()).toContainText('Generation stopped')
  await page.reload()
  await page.locator('.conversation-item > button').first().click()
  await expect(page.locator('.message--assistant').last()).toContainText('partial response')
  await expect(page.locator('.message--assistant').last()).toContainText('Generation stopped')
  // Browser drag-and-drop uses the same authenticated multipart upload path.
  const transfer = await page.evaluateHandle(() => {
    const dt = new DataTransfer(); dt.items.add(new File(['ORION budget is 4200000 yen.'], 'dropped.txt', { type: 'text/plain' })); return dt
  })
  await page.locator('.document-composer').dispatchEvent('drop', { dataTransfer: transfer })
  await expect(page.locator('.attachment--ready')).toHaveCount(6)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Delete: budget.txt', exact: true }).click()
  await expect(page.locator('.attachment')).toHaveCount(5)
  await expect(page.locator('.message-sources').filter({ hasText: 'budget.txt' })).toHaveCount(0)
  await attachment.setInputFiles({ name: 'invalid.pdf', mimeType: 'application/pdf', buffer: Buffer.from('invalid pdf') })
  await expect(page.locator('.chat-error')).toContainText('File content does not match')
  await page.getByRole('checkbox', { name: 'Use for this question: dropped.txt' }).uncheck()
  await send('Chat still works')
  await expect(page.locator('.message--assistant').last()).toContainText('ordinary chat response')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('button', { name: 'Attach files', exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/rag-mobile.png', fullPage: true })
  expect(failures).toEqual([])
  expect(fs.existsSync(path.resolve('test-results/rag-desktop.png'))).toBe(true)
})
